// Generates src/_embedded_ui.ts from the shared Vite build in ../web/dist.
// The Temps GitHub installer does not run package scripts, so the generated
// file is committed. Re-run after changing anything under web/.

import { execSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { extname, join, relative } from "node:path";

const webDir = join(import.meta.dirname, "..", "..", "web");
const distDir = join(webDir, "dist");
const outFile = join(import.meta.dirname, "..", "src", "_embedded_ui.ts");

if (!existsSync(join(webDir, "node_modules"))) execSync("bun install --frozen-lockfile", { cwd: webDir, stdio: "inherit" });
execSync("bun run build", { cwd: webDir, stdio: "inherit" });

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const mime: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "application/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".woff2": "font/woff2",
  ".png": "image/png",
};

const files = walk(distDir).sort();
let code = `// AUTO-GENERATED by scripts/embed-assets.ts from ../web/dist — do not edit.
import type { EmbeddedAssets, EmbeddedFile } from "@temps-sdk/plugin";

const assets: EmbeddedAssets = new Map<string, EmbeddedFile>();
`;
for (const file of files) {
  const path = relative(distDir, file).replaceAll("\\", "/");
  const content = readFileSync(file).toString("base64");
  code += `assets.set(${JSON.stringify(path)}, { content: Buffer.from(${JSON.stringify(content)}, "base64"), contentType: ${JSON.stringify(mime[extname(file)] ?? "application/octet-stream")}, immutable: ${path !== "index.html"} });\n`;
}
code += "\nexport { assets as embeddedAssets };\n";
mkdirSync(join(import.meta.dirname, "..", "src"), { recursive: true });
writeFileSync(outFile, code);
console.log(`Embedded ${files.length} files into ${relative(process.cwd(), outFile)}`);
